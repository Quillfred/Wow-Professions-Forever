#!/usr/bin/env python3
"""Gathering spots for the map pins: tools/node_points.json -> SkillRoute/NodeSpots.lua.

Every spot of every Mining and Herbalism node, per zone map, packed as in
node_points.json ("xxxyyy": map units x 10, one after another), so the addon decodes only
the zones you look at. Models of the same node (tools/import_nodes.py SAME_NODE: the
Amber chunks are Copper Veins) are merged under the node's name, with the game's names
for them kept as aliases (a gather of "Large Chunk of Amber" is a Copper Vein).

Usage: python3 -I tools/gen_nodes.py [--empty]
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from import_nodes import SAME_NODE  # noqa: E402

KIND = {"186": "ore", "182": "herb"}


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    # --empty: no spots (NO_WOWHEAD=1 tools/build_all.sh); the map pins then show only your finds
    empty = "--empty" in sys.argv
    pts = {"lines": {}, "points": {}} if empty else json.load(open(os.path.join(HERE, "node_points.json"), encoding="utf-8"))
    kinds, spots = {}, {}
    for line, names in pts["lines"].items():
        for name in names:
            to = SAME_NODE.get(name, name)
            kinds[to] = KIND[line]
            for m, packed in pts["points"][name].items():
                cur = spots.setdefault(to, {}).get(int(m), "")
                # merged models: keep every spot once
                have = {cur[i:i + 6] for i in range(0, len(cur), 6)}
                add = "".join(packed[i:i + 6] for i in range(0, len(packed), 6) if packed[i:i + 6] not in have)
                spots[to][int(m)] = cur + add
    out = ["-- GENERATED by tools/gen_nodes.py from tools/node_points.json. Do not edit.",
           "-- Where each herb and ore node can spawn, per zone map: \"xxxyyy\" = x, y in map units x 10.",
           "local _, ns = ...",
           "ns.NodeSpots = {",
           "  alias = { " + ", ".join(f"[{lua_str(a)}]={lua_str(b)}" for a, b in sorted(SAME_NODE.items())) + " },",
           "  kind = {"]
    for name in sorted(kinds):
        out.append(f"    [{lua_str(name)}]={lua_str(kinds[name])},")
    out += ["  },", "  spots = {"]
    total = 0
    for name in sorted(spots):
        maps = spots[name]
        total += sum(len(v) // 6 for v in maps.values())
        out.append(f"    [{lua_str(name)}]={{" + ",".join(f"[{m}]={lua_str(maps[m])}" for m in sorted(maps)) + "},")
    out += ["  },", "}", ""]
    dst = os.path.join(HERE, "..", "SkillRoute", "NodeSpots.lua")
    open(dst, "w", encoding="utf-8").write("\n".join(out))
    print(f"{len(spots)} nodes, {total} spots -> SkillRoute/NodeSpots.lua ({os.path.getsize(dst) // 1024} KB)")


if __name__ == "__main__":
    main()
